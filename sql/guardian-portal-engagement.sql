-- Imam Academy v11.2.0 Stage 4.1 — Guardian Engagement Tracking
-- Tracks portal study activity for phone+PIN guardian sessions only.
-- Additive backend-only migration. Local application Schema remains 12.
-- Requires guardian-portal-login.sql to be installed first.

create table if not exists public.guardian_portal_activity_events (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  guardian_account_id uuid not null references public.guardian_portal_accounts(id) on delete cascade,
  session_token uuid references public.guardian_portal_sessions(session_token) on delete set null,
  student_ref text not null,
  event_type text not null,
  event_count integer not null default 1,
  context jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  constraint guardian_portal_activity_student_ref_format check (student_ref ~ '^[0-9a-f]{64}$'),
  constraint guardian_portal_activity_count_range check (event_count between 1 and 30),
  constraint guardian_portal_activity_context_object check (jsonb_typeof(context)='object'),
  constraint guardian_portal_activity_type_allowed check (event_type in (
    'portal_open','student_view','assignment_view','correction_view',
    'tahfeez_open','tahfeez_start','ayah_listen','repeat_complete','tahfeez_complete',
    'assignment_load','correction_practice_open','correction_audio_play','assignment_audio_share'
  ))
);

alter table public.guardian_portal_activity_events enable row level security;
revoke all on table public.guardian_portal_activity_events from public, anon, authenticated;

create index if not exists guardian_portal_activity_owner_student_time_idx
  on public.guardian_portal_activity_events(owner_user_id,student_ref,occurred_at desc);
create index if not exists guardian_portal_activity_account_time_idx
  on public.guardian_portal_activity_events(guardian_account_id,occurred_at desc);
create index if not exists guardian_portal_activity_type_time_idx
  on public.guardian_portal_activity_events(event_type,occurred_at desc);

-- Extend the existing session read RPC with the opaque student_ref required to
-- attribute guardian activity to the correct student. Existing clients ignore
-- the additional field, so this remains backwards compatible.
create or replace function public.guardian_portal_session_read(p_session uuid)
returns jsonb
language sql
security definer
stable
set search_path = public, extensions, pg_temp
as $$
  select jsonb_build_object(
    'expires_at',sess.expires_at,
    'students',coalesce((
      select jsonb_agg(jsonb_build_object(
        'student_ref',s.student_ref,
        'snapshot',s.snapshot,
        'updated_at',s.updated_at
      ) order by s.snapshot#>>'{student,name}')
      from public.guardian_portal_shares s
      join public.guardian_portal_accounts a on a.id=s.guardian_account_id
      where a.id=any(sess.account_ids)
        and a.disabled_at is null
        and exists(select 1 from public.app_users u where u.user_id=s.owner_user_id and u.status='active')
    ),'[]'::jsonb)
  )
  from public.guardian_portal_sessions sess
  where sess.session_token=p_session
    and sess.revoked_at is null
    and sess.expires_at>now()
  limit 1;
$$;

-- Public, but only a valid opaque guardian session can write activity and only
-- for a student that is actually authorized by that session. No IP address,
-- browser fingerprint, phone number, message content, or audio is stored.
create or replace function public.guardian_portal_activity_log(
  p_session uuid,
  p_student_ref text,
  p_event_type text,
  p_event_count integer default 1,
  p_context jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_account_id uuid;
  v_owner_id uuid;
  v_count integer := greatest(1,least(coalesce(p_event_count,1),30));
  v_context jsonb := coalesce(p_context,'{}'::jsonb);
  v_dedupe boolean := false;
begin
  if p_session is null then return false; end if;
  if p_student_ref is null or p_student_ref !~ '^[0-9a-f]{64}$' then return false; end if;
  if p_event_type is null or p_event_type not in (
    'portal_open','student_view','assignment_view','correction_view',
    'tahfeez_open','tahfeez_start','ayah_listen','repeat_complete','tahfeez_complete',
    'assignment_load','correction_practice_open','correction_audio_play','assignment_audio_share'
  ) then return false; end if;
  if jsonb_typeof(v_context)<>'object' or octet_length(v_context::text)>2048 then v_context='{}'::jsonb; end if;

  select s.guardian_account_id,s.owner_user_id
  into v_account_id,v_owner_id
  from public.guardian_portal_sessions sess
  join public.guardian_portal_shares s
    on s.guardian_account_id=any(sess.account_ids)
   and s.student_ref=p_student_ref
  join public.guardian_portal_accounts a on a.id=s.guardian_account_id
  where sess.session_token=p_session
    and sess.revoked_at is null
    and sess.expires_at>now()
    and a.disabled_at is null
    and exists(select 1 from public.app_users u where u.user_id=s.owner_user_id and u.status='active')
  limit 1;

  if v_account_id is null or v_owner_id is null then return false; end if;

  -- Page/view events are de-duplicated for five minutes so refreshes do not
  -- artificially inflate guardian engagement. Playback/repeat events are not
  -- de-duplicated because each completion is meaningful study activity.
  v_dedupe := p_event_type in ('portal_open','student_view','assignment_view','correction_view','tahfeez_open','assignment_load','correction_practice_open');
  if v_dedupe and exists(
    select 1 from public.guardian_portal_activity_events e
    where e.guardian_account_id=v_account_id
      and e.student_ref=p_student_ref
      and e.event_type=p_event_type
      and e.occurred_at>now()-interval '5 minutes'
  ) then return true; end if;

  insert into public.guardian_portal_activity_events(
    owner_user_id,guardian_account_id,session_token,student_ref,event_type,event_count,context
  ) values(v_owner_id,v_account_id,p_session,p_student_ref,p_event_type,v_count,v_context);

  return true;
exception when others then
  -- Engagement logging must never break the guardian learning flow.
  return false;
end;
$$;

-- Teacher-only summary. Returns all phone/PIN-linked students, including those
-- with zero events, so the teacher can see who has not opened the portal.
create or replace function public.guardian_portal_activity_summary(p_days integer default 7)
returns jsonb
language plpgsql
security definer
stable
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_days integer := greatest(1,least(coalesce(p_days,7),90));
  v_since timestamptz;
  v_result jsonb;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED'; end if;
  if not exists(select 1 from public.app_users u where u.user_id=v_uid and u.status='active') then
    raise exception 'ACTIVE_ACCOUNT_REQUIRED';
  end if;
  v_since := now()-(v_days||' days')::interval;

  select jsonb_build_object(
    'days',v_days,
    'generated_at',now(),
    'rows',coalesce(jsonb_agg(row_to_json(x)::jsonb order by x.student_name),'[]'::jsonb)
  ) into v_result
  from (
    select
      s.student_ref,
      coalesce(s.snapshot#>>'{student,name}','طالب') as student_name,
      a.phone_last4,
      max(e.occurred_at) as last_activity_at,
      max(e.occurred_at) filter(where e.event_type='portal_open') as last_portal_open_at,
      max(e.occurred_at) filter(where e.event_type in ('tahfeez_open','tahfeez_start','ayah_listen','repeat_complete','tahfeez_complete')) as last_tahfeez_at,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=now()-interval '24 hours' and e.event_type='portal_open'),0)::integer as portal_visits_24h,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='portal_open'),0)::integer as portal_visits,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='tahfeez_open'),0)::integer as tahfeez_opens,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='tahfeez_start'),0)::integer as tahfeez_starts,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='ayah_listen'),0)::integer as ayah_listens,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='repeat_complete'),0)::integer as repeat_completions,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='tahfeez_complete'),0)::integer as tahfeez_completions,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='assignment_view'),0)::integer as assignment_views,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='correction_view'),0)::integer as correction_views,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='correction_audio_play'),0)::integer as correction_audio_plays,
      coalesce(sum(e.event_count) filter(where e.occurred_at>=v_since and e.event_type='assignment_audio_share'),0)::integer as assignment_audio_shares,
      count(distinct (e.occurred_at at time zone 'UTC')::date) filter(where e.occurred_at>=v_since)::integer as active_days
    from public.guardian_portal_shares s
    join public.guardian_portal_accounts a on a.id=s.guardian_account_id
    left join public.guardian_portal_activity_events e
      on e.owner_user_id=s.owner_user_id and e.student_ref=s.student_ref
    where s.owner_user_id=v_uid and s.guardian_account_id is not null and a.disabled_at is null
    group by s.student_ref,s.snapshot,a.phone_last4
  ) x;

  return coalesce(v_result,jsonb_build_object('days',v_days,'generated_at',now(),'rows','[]'::jsonb));
end;
$$;

revoke all on function public.guardian_portal_activity_log(uuid,text,text,integer,jsonb) from public;
revoke all on function public.guardian_portal_activity_summary(integer) from public;

-- Public execution is safe because the logger validates the opaque session and
-- student authorization internally. The summary remains teacher-authenticated.
grant execute on function public.guardian_portal_activity_log(uuid,text,text,integer,jsonb) to anon, authenticated;
grant execute on function public.guardian_portal_activity_summary(integer) to authenticated;

-- Stage 4.1 privacy/security notes:
-- • No phone number, PIN, message content, audio bytes, IP address, or user-agent is stored.
-- • A guardian can log activity only for students in their valid phone+PIN session.
-- • Teachers can read summaries only for their own guardian-linked students.
-- • Activity logging is additive and never modifies student/session learning records.
-- • Local application Schema remains 12.
