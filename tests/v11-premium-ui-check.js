const fs=require('fs');
const path=require('path');
const vm=require('vm');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
function ok(v,m){if(!v)throw new Error(m)}
const html=read('index.html');
const css=read('v11.css');
const js=read('js/features/v11-ui.js');
const sw=read('sw.js');
const runtime=read('js/core/runtime.js');
const pkg=JSON.parse(read('package.json'));
new vm.Script(js,{filename:'js/features/v11-ui.js'});
ok(pkg.version==='11.8.0','package must be v11.0.0');
ok(runtime.includes("version:'11.8.0',schema:12"),'runtime version/schema mismatch');
ok((html.includes('v11.css?v=11.0.0-s2')||html.includes('v11.css?v=11.4.1-profile-ui')),'v11 stylesheet missing from shell');
ok((html.includes('js/features/v11-ui.js?v=11.0.0-s2')||html.includes('js/features/v11-ui.js?v=11.4.1-profile-ui')),'v11 UI controller missing from shell');
ok(html.includes('class="v11-brand"')&&html.includes('v11-brand-logo'),'premium branded header missing');
ok(sw.includes("quran-pwa-v11.2.0-error1"),'v11 cache generation missing');
ok((sw.includes("'./v11.css?v=11.0.0-s2'")||sw.includes("'./v11.css?v=11.4.1-profile-ui'"))&&(sw.includes("'./js/features/v11-ui.js?v=11.0.0-s2'")||sw.includes("'./js/features/v11-ui.js?v=11.4.1-profile-ui'")),'v11 assets must be offline cached');
ok(css.includes('.v92-primary-card')&&css.includes('.v9-nav')&&css.includes('.v11-connectivity'),'premium home/nav/status styles incomplete');
ok(js.includes("text.textContent=online?'متصل':'محلي'"),'connectivity state wording missing');
ok(!/\bstudents\s*=|\bsessions\s*=/.test(js),'presentation layer must not mutate student/session collections');
console.log('v11-premium-ui-check: PASS');
