'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const source=read('js/features/imam-board-tafsir.js'),board=read('js/features/imam-smart-board.js'),html=read('index.html'),sw=read('sw.js');
const env={window:null,ImamApp:{},S:[{n:'الفاتحة',a:7},{n:'البقرة',a:286}]};env.window=env;
vm.runInNewContext(source,env,{filename:'imam-board-tafsir.js'});
const a=env.ImamApp.BoardTafsir;
assert.equal(typeof a.importFiles,'function');
assert(a.SOURCES.verse.url.startsWith('https://qurancomplex.gov.sa/'),'source must remain official');
assert(a.SOURCES.word.title.includes('غريب القرآن'));
const verse=a.canonical({sura_no:1,aya_no:2,aya_tafseer:'<span class="aya">بِسْمِ اللهِ</span> شرح تجريبي'},'verse');
assert.equal(verse.key,'t:1:2');assert(!verse.content.includes('<span'),'No imported HTML must be inserted');
const word=a.canonical({sura_name:'الفاتحة',aya_no:2,quranic_words:'الرَّحْمَٰنِ',explanation:'شرح تجريبي للكلمة'},'word');
assert.equal(word.key,'w:1:2:الرحمن');
assert.equal(a.normalized('الرَّحْمَٰنِ'),a.normalized('الرحمن'));
assert.equal(a.canonical({sura_no:222,aya_no:2,aya_tafseer:'غير صالح'},'verse'),null);
assert.equal(a.canonical({sura_no:1,aya_no:9,aya_tafseer:'آية خارج السورة'},'verse'),null);
assert.equal(a.canonical({sura_no:1,aya_no:2,explanation:'غريب بلا كلمة'},'word'),null);
const csv=a.parseCSV('sura_no,aya_no,aya_tafseer\r\n1,2,"شرح، تجريبي"\r\n');
assert.equal(csv.length,1);assert.equal(csv[0].aya_tafseer,'شرح، تجريبي');
assert.throws(()=>a.parseCSV('x,y\n"unfinished,value\n'),/غير مغلق/);
assert(html.includes('imam-board-tafsir.js?v=11.12.1-beta.10'));
assert(sw.includes("'./js/features/imam-board-tafsir.js?v=11.12.1-beta.10'"));
assert(board.includes('case \'scienceShareImported\':shareImportedScience();'));
assert(board.includes('data-cmd="scienceImport"'));
assert(board.includes('sourceTitle')&&board.includes('sourceUrl'));
assert(source.includes('indexedDB')&&source.includes('acknowledged')&&source.includes('verified:false'));
